#!/usr/bin/env python3
"""Empires Front (2026-11-07): builds src/client/Lang/{Pt,Es,Ru}.luau from tools/lang/texts*.py.

texts1..5 hold T = [(english, pt, es, ru), ...]: the game's English exactly as the UI writes it, with
%s / %d where code fills in a value and {name} where UIRules.format does. texts6 holds N, the game's
own names (singular and plural). Checks every entry's placeholders and warns about English base words
left in a translation (they would turn into the era's English words in game).

    python3 tools/lang/build.py
"""
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "src", "client", "Lang")
LANGS = [("pt", "Pt", "Português"), ("es", "Es", "Español"), ("ru", "Ru", "Русский")]
PH = re.compile(r"%[-\d.]*[sdfi]")
NAMED = re.compile(r"\{([\w]+)\}")


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def norm(s):
    # (the catalog kept Luau escapes: \n and \" are a newline and a quote in game)
    return s.replace("\\n", "\n").replace('\\"', '"')


def check(key, val, lang, problems):
    kp = PH.findall(key)
    kn = NAMED.findall(key)
    if kn and kp:
        problems.append(f"{lang}: key mixes %-tokens and names: {key!r}")
        return
    if kn:
        for n in NAMED.findall(val):
            if n not in kn:
                problems.append(f"{lang}: unknown name {{{n}}} in {val!r}")
        return
    used = set()
    for n in NAMED.findall(val):
        if not n.isdigit() or not (1 <= int(n) <= len(kp)):
            problems.append(f"{lang}: bad index {{{n}}} for {key!r}")
        else:
            used.add(int(n))
    left = [i for i in range(1, len(kp) + 1) if i not in used]
    vp = PH.findall(val)
    if len(vp) > len(left):
        problems.append(f"{lang}: {len(vp)} tokens for {len(left)} values: {key!r} -> {val!r}")
        return
    for tok, i in zip(vp, left):
        if tok[-1] != kp[i - 1][-1] and not (tok[-1] in "di" and kp[i - 1][-1] in "di"):
            problems.append(f"{lang}: token {tok} takes {kp[i - 1]}: {key!r} -> {val!r}")


def lua_str(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return '"' + out + '"'


def lower_first_words(s):
    return s.lower()


def main():
    rows = []
    for i in range(1, 6):
        mod = load(f"texts{i}")
        for r in mod.T:
            if len(r) != 4:
                sys.exit(f"texts{i}: an entry without 4 strings: {r!r}")
            rows.append((f"texts{i}", tuple(norm(x) for x in r)))
    names = load("texts6").N
    for r in names:
        en, enp, pt, ptp, es, esp, ru, rup = r
        rows.append(("texts6", (en, pt, es, ru)))
        if enp != en:
            rows.append(("texts6", (enp, ptp, esp, rup)))
        # (the lower-case word inside a sentence of its own: "warship", "trade ships")
        for a, b in ((en, (pt, es, ru)),) + (((enp, (ptp, esp, rup)),) if enp != en else ()):
            if a.lower() != a and a.upper() != a:
                rows.append(("texts6", (a.lower(),) + tuple(x.lower() for x in b)))

    # base words the era rewrites: left in a translation they become the era's English
    eras = open(os.path.join(ROOT, "src", "shared", "Data", "Eras.luau"), encoding="utf-8").read()
    base = sorted({a for a, _ in re.findall(r'\{\s*"([^"]+)",\s*"([^"]+)"', eras)}, key=len, reverse=True)
    base_re = [re.compile(r"(?<![\w])" + re.escape(b) + r"(?![\w])") for b in base]

    problems = []
    tables = {c: {} for c, _, _ in LANGS}
    for src, (en, *tr) in rows:
        for (code, _, _), val in zip(LANGS, tr):
            if not val:
                continue
            check(en, val, code, problems)
            for b, rx in zip(base, base_re):
                if rx.search(val) and b not in ("Gold",):
                    problems.append(f"{code}: English base word {b!r} left in {val!r}")
                    break
            old = tables[code].get(en)
            if old is not None and old != val:
                problems.append(f"{code}: {src} redefines {en!r}: {old!r} / {val!r}")
            tables[code][en] = val

    os.makedirs(OUT, exist_ok=True)
    # (one list of the English keys, Lang/Keys; each language a list of values in the same order:
    # the keys are not repeated three times, and a module is small enough to paste into Studio)
    keys = sorted(set().union(*[set(t) for t in tables.values()]))
    lines = [
        "--!strict",
        "-- Empires Front: the interface's English texts that have translations, in the order of the values",
        "-- in Lang/Pt, Es and Ru (generated by tools/lang/build.py from tools/lang/texts*.py; edit those).",
        "return {",
    ]
    lines += [f"\t{lua_str(k)}," for k in keys]
    lines += ["}", ""]
    with open(os.path.join(OUT, "Keys.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Keys.luau: {len(keys)} keys")
    for code, mod_name, label in LANGS:
        t = tables[code]
        lines = [
            "--!strict",
            f"-- Empires Front: the interface in {label}, one value for each of Lang/Keys in order (\"\": none).",
            "-- Generated by tools/lang/build.py from tools/lang/texts*.py; edit those, not this.",
            "return { values = {",
        ]
        lines += [f"\t{lua_str(t.get(k, ''))}," for k in keys]
        lines += ["}, terms = {} }", ""]
        path = os.path.join(OUT, mod_name + ".luau")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
        print(f"{mod_name}.luau: {len(t)} texts")
    for p in problems:
        print("WARN", p)
    print(f"{len(problems)} warnings")


if __name__ == "__main__":
    main()
