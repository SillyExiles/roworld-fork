#!/usr/bin/env python3
"""Empires Front (2026-11-06): the map effects atlas (assets/map_fx/map_fx.png, tools/assets/make_map_fx.py)
as data, so the client draws it itself (Map/MapFxImage: an EditableImage). The uploaded atlas
(Assets/MapFx.id) belongs to the original RoWorld account and the experience may not load it.

Out: src/shared/Assets/MapFxPixels.luau: { w, h, palette = { r, g, b, a ... }, runs = base64 of
(palette index, run length 1..255) byte pairs, row-major }.
usage: python3 tools/assets/make_map_fx_pixels.py"""
import base64
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "assets", "map_fx", "map_fx.png")
OUT = os.path.join(ROOT, "src", "shared", "Assets", "MapFxPixels.luau")

im = Image.open(SRC).convert("RGBA")
w, h = im.size
px = [im.getpixel((x, y)) for y in range(h) for x in range(w)]
px = [p if p[3] > 0 else (0, 0, 0, 0) for p in px]
palette, idx = [], {}
for p in px:
    if p not in idx:
        idx[p] = len(palette)
        palette.append(p)
assert len(palette) <= 256
runs = bytearray()
i = 0
while i < len(px):
    j = i
    while j < len(px) and px[j] == px[i] and j - i < 255:
        j += 1
    runs += bytes((idx[px[i]], j - i))
    i = j
b64 = base64.b64encode(bytes(runs)).decode()
pal = ", ".join(str(v) for p in palette for v in p)
lines = [
    "-- GENERATED by tools/assets/make_map_fx_pixels.py. Do not edit.",
    "-- The map effects atlas (Assets/MapFx rows) as pixels: Map/MapFxImage draws it (EditableImage).",
    "return {",
    f"\tw = {w},",
    f"\th = {h},",
    f"\tpalette = {{ {pal} }},",
]
# the base64 in chunks (no overlong lines)
lines.append("\truns = table.concat({")
for k in range(0, len(b64), 120):
    lines.append(f'\t\t"{b64[k:k + 120]}",')
lines.append("\t}),")
lines.append("}")
open(OUT, "w").write("\n".join(lines) + "\n")
print(OUT, w, h, len(palette), "colors", len(runs) // 2, "runs", len(b64), "b64 chars")
