"""Empires Front (2026-11-01): 16 x 16 pixel-art glyphs for the ecosystem's buildings.

A Temple and a Palace per map (each map its own), and the Fortress and the University. Writes
src/client/UI/PixelBuildings.luau (rows of "W" = white pixel, "." = clear: UI/PixelIcons tints them)
and, with --preview out.png, a sheet to look at.
usage: python3 tools/make_pixel_buildings.py [--preview sheet.png]
"""
import sys

G = {}

def art(name, rows):
    rows = [r for r in rows.strip("\n").split("\n")]
    rows = [r.strip() for r in rows]
    assert len(rows) <= 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
    # bottom-align: pad on top
    pad = 16 - len(rows)
    rows = ["." * 16] * (pad // 2) + rows + ["." * 16] * (pad - pad // 2)
    G[name] = [r.replace("#", "W") for r in rows]

