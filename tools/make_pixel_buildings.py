MAPS = ["rome", "greece", "japan", "china", "mongol", "ottoman", "persia", "russia", "inca", "aztec", "mali",
        "world", "europe", "africa", "northamerica", "southamerica"]


def write_luau(path):
    out = ["--!strict",
           "-- GENERATED by tools/make_pixel_buildings.py: 16 x 16 pixel-art glyphs (\"W\" white, \".\" clear) for",
           "-- the ecosystem's buildings: a Temple and a Palace per map (temple_<map>, palace_<map>), the Fortress",
           "-- and the University. UI/PixelIcons adds them to its GLYPHS.",
           "return {"]
    for name in sorted(G):
        out.append("\t%s = {" % name)
        for r in G[name]:
            out.append('\t\t"%s",' % r)
        out.append("\t},")
    out.append("}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def preview(path):
    from PIL import Image, ImageDraw
    names = []
    for m in MAPS:
        names += ["temple_" + m, "palace_" + m]
    names += ["fortress", "university"]
    S = 6
    cell = 16 * S + 16
    cols = 8
    rows = (len(names) + cols - 1) // cols
    img = Image.new("RGB", (cols * cell, rows * (cell + 14)), (40, 44, 60))
    d = ImageDraw.Draw(img)
    for i, n in enumerate(names):
        cx, cy = (i % cols) * cell, (i // cols) * (cell + 14)
        d.rectangle([cx + 4, cy + 4, cx + cell - 4, cy + cell - 4], fill=(150, 60, 60))
        for y, r in enumerate(G[n]):
            for x, ch in enumerate(r):
                if ch == "W":
                    d.rectangle([cx + 8 + x * S, cy + 8 + y * S, cx + 8 + x * S + S - 1, cy + 8 + y * S + S - 1], fill=(255, 255, 255))
        d.text((cx + 4, cy + cell - 2), n.replace("temple_", "T ").replace("palace_", "P "), fill=(230, 230, 230))
    img.save(path)


if __name__ == "__main__":
    write_luau("src/client/UI/PixelBuildings.luau")
    if "--preview" in sys.argv:
        preview(sys.argv[sys.argv.index("--preview") + 1])
    print(len(G), "glyphs")
