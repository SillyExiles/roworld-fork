def rgba(name):
    out = bytearray()
    for row in SPR[name]:
        for ch in row:
            c = PAL[ch]
            out += bytes((0, 0, 0, 0)) if c is None else bytes((c[0], c[1], c[2], 255))
    return out


def write():
    lines = [
        "--!strict",
        "-- GENERATED by tools/make_siege_art.py: the siege weapons' glyphs (16 x 16, \"W\" white, \".\" clear;",
        "-- UI/PixelIcons tints them): the Siege Workshop (silo_*), the Watchtower (sam_*), the bombard (atom_*),",
        "-- fire (hydrogen_*) and the plague, and which of them each map shows (by_map: icon -> map -> glyph).",
        "return {",
        "\tglyphs = {",
    ]
    for name in sorted(G):
        lines.append(f"\t\t{name} = {{")
        for r in G[name]:
            lines.append(f'\t\t\t"{r}",')
        lines.append("\t\t},")
    lines.append("\t},")
    lines.append("\tby_map = {")
    for i, icon in enumerate(("silo", "sam", "atom", "hydrogen")):
        lines.append(f"\t\t{icon} = {{")
        for m in sorted(STYLES):
            lines.append(f'\t\t\t{m} = "{icon}_{STYLES[m][i]}",')
        lines.append("\t\t},")
    lines.append("\t},")
    lines.append("}")
    open(os.path.join(ROOT, "src", "client", "UI", "SiegeGlyphs.luau"), "w").write("\n".join(lines) + "\n")

    lines = [
        "-- GENERATED by tools/make_siege_art.py: the siege weapons in flight (16 x 16 RGBA in colour, base64),",
        "-- and which each era fires (by_era: atom = its bombard, hydrogen = its fire, plague). Map/SiegeArt.",
        "return {",
        "\tsize = 16,",
        "\tsprites = {",
    ]
    for name in sorted(SPR):
        lines.append(f'\t\t{name} = "{base64.b64encode(bytes(rgba(name))).decode()}",')
    lines.append("\t},")
    lines.append("\tby_era = {")
    for era in sorted(ERA_SPRITES):
        a, h = ERA_SPRITES[era]
        lines.append(f'\t\t{era} = {{ atom = "{a}", hydrogen = "{h}", plague = "plague" }},')
    lines.append("\t},")
    lines.append("}")
    open(os.path.join(ROOT, "src", "client", "Map", "SiegeData.luau"), "w").write("\n".join(lines) + "\n")


def preview(path):
    from PIL import Image
    names = sorted(G)
    cols = 8
    scale = 6
    rows_n = (len(names) + cols - 1) // cols + 2
    im = Image.new("RGBA", (cols * 18 * scale, rows_n * 18 * scale), (40, 52, 70, 255))
    for i, n in enumerate(names):
        ox, oy = (i % cols) * 18 * scale, (i // cols) * 18 * scale
        for y, r in enumerate(G[n]):
            for x, ch in enumerate(r):
                if ch == "W":
                    for dy in range(scale):
                        for dx in range(scale):
                            im.putpixel((ox + (x + 1) * scale + dx, oy + (y + 1) * scale + dy), (240, 240, 240, 255))
    base = ((len(names) + cols - 1) // cols) * 18 * scale
    for i, n in enumerate(sorted(SPR)):
        ox, oy = (i % cols) * 18 * scale, base + (i // cols) * 18 * scale
        for y, r in enumerate(SPR[n]):
            for x, ch in enumerate(r):
                c = PAL[ch]
                if c is not None:
                    for dy in range(scale):
                        for dx in range(scale):
                            im.putpixel((ox + (x + 1) * scale + dx, oy + (y + 1) * scale + dy), c + (255,))
    im.save(path)


if __name__ == "__main__":
    write()
    if "--preview" in sys.argv:
        preview(sys.argv[sys.argv.index("--preview") + 1])
    print(len(G), "glyphs,", len(SPR), "sprites")
