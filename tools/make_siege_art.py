#!/usr/bin/env python3
"""Empires Front (2026-11-06): the siege weapons' pixel art.

1. Glyphs, 16 x 16, white on clear ("W" / "."), tinted by the UI (UI/PixelIcons): the Siege Workshop
   (the silo), the Watchtower (the SAM) and the three weapons (atom = the era's bombard, hydrogen = fire,
   plague), each in the style of the map in play. Written to src/client/UI/SiegeGlyphs.luau as
   { glyphs = { name = rows }, by_map = { icon = { map = glyph } } }.
2. Sprites in flight, 16 x 16 RGBA in colour (not tinted): stones, cannonballs, rockets, shells, fire
   pots, fire arrows, plague bundles. Written to src/client/Map/SiegeData.luau as base64 RGBA by name,
   with by_era = { era = { atom = name, hydrogen = name, plague = name } } for Map/SiegeArt.

usage: python3 tools/make_siege_art.py [--preview sheet.png]
"""
import base64
import os
