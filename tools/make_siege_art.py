ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ------------------------------------------------------------------------------------------- glyphs
G = {}


def glyph(name, art):
    rows = [r.strip() for r in art.strip("\n").split("\n")]
    assert len(rows) <= 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
    pad = 16 - len(rows)
    rows = ["." * 16] * (pad // 2) + rows + ["." * 16] * (pad - pad // 2)
    G[name] = [r.replace("#", "W") for r in rows]


