def write():
    """Each glyph as 64 hex digits (16 rows of 16 bits, the leftmost pixel the high bit), unpacked to
    rows of "W" / "." when the module loads."""
    out = ["--!strict",
           "-- GENERATED by tools/make_era_buildings.py: 16 x 16 pixel-art glyphs, the buildings of each era map in",
           "-- its own style (<kind>_<era>). Stored as 16 rows of 16 bits in hex (the leftmost pixel the high bit)",
           "-- and unpacked to rows of \"W\" (white) / \".\" (clear). UI/PixelIcons adds them to its GLYPHS and shows",
           "-- them on the era maps (by_map: map -> era); other maps keep the usual icons.",
           "local DATA = {"]
    for name in sorted(G):
        h = "".join("%04x" % int(r.replace("W", "1").replace(".", "0"), 2) for r in G[name])
        out.append('\t%s = "%s",' % (name, h))
    out.append("}")
    out.append("local glyphs: { [string]: { string } } = {}")
    out.append("for name, hex in DATA do")
    out.append("\tlocal rows = table.create(16)")
    out.append("\tfor y = 0, 15 do")
    out.append("\t\tlocal v = tonumber(string.sub(hex, y * 4 + 1, y * 4 + 4), 16) or 0")
    out.append("\t\tlocal r = table.create(16)")
    out.append("\t\tfor x = 0, 15 do")
    out.append("\t\t\tr[x + 1] = if bit32.btest(v, bit32.lshift(1, 15 - x)) then \"W\" else \".\"")
    out.append("\t\tend")
    out.append("\t\trows[y + 1] = table.concat(r)")
    out.append("\tend")
    out.append("\tglyphs[name] = rows")
    out.append("end")
    out.append("return {")
    out.append("\tglyphs = glyphs,")
    out.append("\tby_map = {")
    for m in sorted(BY_MAP):
        out.append('\t\t%s = "%s",' % (m, BY_MAP[m]))
    out.append("\t},")
    out.append("\tkinds = {")
    for k in KINDS:
        out.append("\t\t%s = true," % k)
    out.append("\t},")
    out.append("}")
    with open(os.path.join(ROOT, "src/client/UI/EraBuildings.luau"), "w") as f:
        f.write("\n".join(out) + "\n")


PLATE = [(176, 64, 58), (58, 110, 176), (70, 150, 80), (190, 150, 50)]


def preview(path, eras=None):
    from PIL import Image, ImageDraw
    eras = eras or [e for e in ERAS if any(k + "_" + e in G for k in KINDS)]
    S_ = int(os.environ.get("SCALE", "4"))
    cell = 16 * S_ + 12
    W = 70 + len(KINDS) * cell
    H = 18 + len(eras) * cell
    img = Image.new("RGB", (W, H), (36, 40, 52))
    d = ImageDraw.Draw(img)
    for j, k in enumerate(KINDS):
        d.text((70 + j * cell + 4, 4), k[:9], fill=(220, 220, 220))
    for i, e in enumerate(eras):
        y0 = 18 + i * cell
        d.text((4, y0 + cell // 2 - 6), e, fill=(220, 220, 220))
        for j, k in enumerate(KINDS):
            n = k + "_" + e
            x0 = 70 + j * cell
            col = PLATE[i % len(PLATE)]
            d.rounded_rectangle([x0 + 2, y0 + 2, x0 + cell - 3, y0 + cell - 3], radius=10, fill=col)
            rows = G.get(n)
            if rows is None:
                continue
            for y, r in enumerate(rows):
                for x, ch in enumerate(r):
                    if ch == "W":
                        px, py = x0 + 6 + x * S_, y0 + 6 + y * S_
                        d.rectangle([px, py, px + S_ - 1, py + S_ - 1], fill=(255, 255, 255))
    img.save(path)


