#!/usr/bin/env python3
"""Empires Front (2026-11-06): the buildings of every era in its own pixel art.

16 x 16 glyphs, white on clear ("W" / "."), tinted by the UI (UI/PixelIcons) and drawn on the map's
plates (Map/StructureLayer): the City, Port, Defense Post, Factory (the era's road hub), Mine, Market,
Farm, Forge, Border Wall, Barracks, Fortress, University and the Warship's build icon, one set per era
map. The Temple and the Palace (tools/make_pixel_buildings.py) and the siege weapons
(tools/make_siege_art.py) have their own. Maps without an era of their own (Europe, Africa, the
Americas) keep the usual icons.

Writes src/client/UI/EraBuildings.luau (each glyph packed as 64 hex digits), which returns
    { glyphs = { "<kind>_<era>" = rows }, by_map = { map = era }, kinds = { kind = true } }
usage: python3 tools/make_era_buildings.py [--preview sheet.png]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

KINDS = ["city", "port", "defense", "factory", "mine", "market", "farm", "forge", "wall", "barracks",
         "fortress", "university", "warship"]
ERAS = ["rome", "greece", "persia", "china", "mongol", "ottoman", "japan", "inca", "aztec", "mali",
        "russia", "britain"]
# the era maps (Data/MapList: World is played in 1897 Britain)
BY_MAP = {e: e for e in ERAS if e != "britain"}
BY_MAP["world"] = "britain"

G = {}
ERRORS = []


def _put(name, rows):
    rows = [r.replace("#", "W") for r in rows]
    if len(rows) > 16:
        ERRORS.append("%s: %d rows" % (name, len(rows)))
    for i, r in enumerate(rows):
        if len(r) != 16:
            ERRORS.append("%s row %d: %r (%d)" % (name, i, r, len(r)))
    pad = 16 - len(rows)
    # bottom-heavy: a little more room above than below
    top = (pad + 1) // 2
    G[name] = ["." * 16] * top + rows + ["." * 16] * (pad - top)


def A(name, art):
    """Full rows, 16 wide."""
    _put(name, [r.strip() for r in art.strip("\n").split("\n")])


def S(name, art):
    """Left halves, 8 wide, mirrored into 16 (symmetric glyphs)."""
    rows = []
    for r in art.strip("\n").split("\n"):
        r = r.strip()
        if len(r) != 8:
            ERRORS.append("%s half %r (%d)" % (name, r, len(r)))
        rows.append(r + r[::-1])
    _put(name, rows)


