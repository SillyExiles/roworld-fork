#!/usr/bin/env python3
"""Empires Front: map picker previews. Renders every map in the registry with the game's pixel-art terrain
(tools/maps/preview_paint.py, the same rules as client/Map/MapSurface), marks the objective's sites with gold
stars, scales it to PREVIEW_W pixels wide and writes src/shared/Assets/MapPreviews.luau:
{ [map id] = { w, h, data = base64(zstd(RGB bytes)) } } (client/UI/MapPreview decodes it).
Usage (repo root): PYTHONPATH=<dir with zstandard> python3 tools/maps/make_previews.py [--png <dir>]"""
import argparse, base64, os, re, sys
import importlib.util
import numpy as np
import zstandard
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
spec = importlib.util.spec_from_file_location("preview_paint", os.path.join(HERE, "preview_paint.py"))
pp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pp)
PREVIEW_W = 240
STAR = ["...O...", "..OYO..", "OOYHYOO", ".OYYYO.", "..OYO..", ".OYOYO.", ".OO.OO."]
STAR_COL = {"O": (90, 52, 12), "Y": (245, 194, 43), "H": (255, 240, 154)}


def module_paths():
    s = open(os.path.join(REPO, "src/shared/Data/MapList.luau")).read()
    for m in re.finditer(r'\{ id = "([^"]+)", name = "[^"]+", module = "([^"]+)".*?\}(,|$)', s):
        mid, mod = m.group(1), m.group(2)
        for d in ("src/shared/Data/Maps", "src/server/MapData"):
            p = os.path.join(REPO, d, mod + ".luau")
            if os.path.exists(p):
                yield mid, p


def render(path):
    s = open(path).read()
    W = int(re.search(r"\bwidth = (\d+)", s).group(1))
    H = int(re.search(r"\bheight = (\d+)", s).group(1))
    lt = float(re.search(r"\blat_top = ([-\d.]+)", s).group(1))
    lb = float(re.search(r"\blat_bottom = ([-\d.]+)", s).group(1))
    t = re.search(r'\bterrain = "([^"]+)"', s).group(1)
    tb = zstandard.ZstdDecompressor().decompress(base64.b64decode(t), W * H)
    img = Image.fromarray(pp.paint(tb, W, H, lt, lb))
    h = round(H * PREVIEW_W / W)
    small = img.resize((PREVIEW_W, h), Image.BOX)
    sites = re.search(r"\bsites = \{(.*?)\n\t\}", s, re.S)
    if sites:
        for m in re.finditer(r"x = (\d+), y = (\d+)", sites.group(1)):
            cx, cy = round(int(m.group(1)) * PREVIEW_W / W), round(int(m.group(2)) * h / H)
            for dy, row in enumerate(STAR):
                for dx, ch in enumerate(row):
                    if ch in STAR_COL and 0 <= cx + dx - 3 < PREVIEW_W and 0 <= cy + dy - 3 < h:
                        small.putpixel((cx + dx - 3, cy + dy - 3), STAR_COL[ch])
    return small


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--png")
    a = ap.parse_args()
    lines = ["-- GENERATED by tools/maps/make_previews.py: the map picker's previews (RGB, base64(zstd)). Do not edit.",
             "return {"]
    for mid, path in module_paths():
        im = render(path).convert("RGB")
        raw = im.tobytes()
        z = zstandard.ZstdCompressor(level=19).compress(raw)
        lines.append('\t%s = { w = %d, h = %d, data = "%s" },' % (mid, im.width, im.height, base64.b64encode(z).decode()))
        print(mid, im.size, len(z), "bytes")
        if a.png:
            os.makedirs(a.png, exist_ok=True)
            im.resize((im.width * 2, im.height * 2), Image.NEAREST).save(os.path.join(a.png, "preview_%s.png" % mid))
    lines.append("}")
    open(os.path.join(REPO, "src/shared/Assets/MapPreviews.luau"), "w").write("\n".join(lines) + "\n")


main()
